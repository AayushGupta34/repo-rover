def finding_slugs(finding: dict[str, Any]) -> set[str]:
    """Catalogue rules behind a finding: its own rule, or detector evidence."""
    slugs = set()
    if finding.get("catalog_slug"):
        slugs.add(finding["catalog_slug"])
    for item in finding.get("evidence") or []:
        if isinstance(item, dict) and item.get("kind") == "detector" and item.get("detector"):
            slugs.add(item["detector"])
    return slugs


def discover_routes(repo_root: str | os.PathLike | None) -> tuple[list[str], str]:
    """(parameter-free GET paths, a POST-looking path) found in route definitions."""
    paths: list[str] = []
    post_path = "/"
    if repo_root and os.path.isdir(repo_root):
        root = Path(os.path.realpath(repo_root))
        post_pattern = re.compile(r"""(?:\.post\(\s*|methods\s*=\s*\[[^\]]*POST[^\]]*\][^\n]*|@\w+\.post\(\s*)["'`](/[^"'`\s]*)["'`]""")
        for relative in iter_repo_files(root):
            if not relative.endswith((".js", ".ts", ".mjs", ".cjs", ".py")):
                continue
            try:
                _, lines = load_text_file(root / relative)
            except RepoPathError:
                continue
            text = "\n".join(lines)
            for pattern in _ROUTE_PATTERNS:
                for match in pattern.finditer(text):
                    path = match.group(1)
                    if SAFE_ROUTE.match(path) and path not in paths:
                        paths.append(path)
            if post_path == "/":
                found = re.search(r"""\.post\(\s*["'`](/[^"'`\s:<{*]*)["'`]""", text) or post_pattern.search(text)
                if found and SAFE_ROUTE.match(found.group(1)):
                    post_path = found.group(1)
    if "/" not in paths:
        paths.insert(0, "/")
    return paths[:MAX_ROUTES], post_path


def discover_selectors(repo_root: str | os.PathLike | None) -> dict[str, str]:
    """Selectors for the submit control and file input, if they carry an id."""
    selectors = {"submit": DEFAULT_SUBMIT_SELECTOR, "file_input": DEFAULT_FILE_INPUT_SELECTOR}
    if not repo_root or not os.path.isdir(repo_root):
        return selectors
    root = Path(os.path.realpath(repo_root))
    patterns = {
        "submit": re.compile(r"""<(?:button|input)\b[^>]*\btype=["']submit["'][^>]*\bid=["']([^"']+)["']|<(?:button|input)\b[^>]*\bid=["']([^"']+)["'][^>]*\btype=["']submit["']""", re.IGNORECASE),
        "file_input": re.compile(r"""<input\b[^>]*\btype=["']file["'][^>]*\bid=["']([^"']+)["']|<input\b[^>]*\bid=["']([^"']+)["'][^>]*\btype=["']file["']""", re.IGNORECASE),
    }
    for relative in iter_repo_files(root):
        if not relative.lower().endswith((".html", ".htm", ".jsx", ".tsx", ".vue", ".svelte")):
            continue
        try:
            _, lines = load_text_file(root / relative)
        except RepoPathError:
            continue
        text = "\n".join(lines)
        for key, pattern in patterns.items():
            match = pattern.search(text)
            if match and selectors[key] in (DEFAULT_SUBMIT_SELECTOR, DEFAULT_FILE_INPUT_SELECTOR):
                candidate = "#" + (match.group(1) or match.group(2))
                if SAFE_SELECTOR.match(candidate):
                    selectors[key] = candidate
    return selectors


def _render(template: dict[str, Any], experiment: dict[str, Any], routes: list[str], post_path: str, name: str,
            selectors: dict[str, str] | None = None) -> str:
    is_k6 = template["tool"] == "k6"
    guard = _JS_LOCAL_GUARD.replace("__ENV_GETTER__('BASE_URL')", "__ENV.BASE_URL" if is_k6 else "process.env.BASE_URL")
    source = template["source"]
    if "__COMMON__" in source:
        source = source.replace("__COMMON__", K6_COMMON)
    selectors = selectors or {}
    # Every value that comes from the analysed repository or from a model is
    # either JSON-encoded (when it is data) or reduced to a safe single line
    # (when it sits in a comment). Nothing is pasted in as raw text.
    routes = [route for route in routes if SAFE_ROUTE.match(route)] or ["/"]
    post_path = post_path if SAFE_ROUTE.match(post_path) else "/"
    replacements = {
        "__GUARD__": guard,
        "__DEFAULT_BASE_URL__": json.dumps(DEFAULT_BASE_URL),
        "__EXPERIMENT_ID__": safe_comment(experiment["id"], 12),
        "__FINDINGS__": safe_comment(", ".join(f"{f['id']} [{f['label']}] {f['title']}" for f in experiment["findings"])),
        "__HYPOTHESIS__": safe_comment(experiment["hypothesis"]),
        "__PATHS__": json.dumps(routes),
        "__POST_PATH__": json.dumps(post_path),
        "__SUBMIT_SELECTOR__": json.dumps(selectors.get("submit", DEFAULT_SUBMIT_SELECTOR)),
        "__FILE_INPUT_SELECTOR__": json.dumps(selectors.get("file_input", DEFAULT_FILE_INPUT_SELECTOR)),
        "__NAME__": re.sub(r"[^A-Za-z0-9_\-]", "", name),
    }
    for token, value in replacements.items():
        source = source.replace(token, value)
    return source


def build_plan(
    findings: list[dict[str, Any]],
    stack_trigger: str = "unknown",
    target_repo: str | None = None,
    routes: list[str] | None = None,
    post_path: str = "/",
) -> dict[str, Any]:
    """The plan as data. Only evidence-backed findings can justify an experiment."""
    backed = [f for f in findings if f.get("label") in ("Verified", "Detector-Hit")]
    experiments = []
    for key, template in TEMPLATES.items():
        matched = [f for f in backed if finding_slugs(f) & template["slugs"]]
        if not matched:
            continue
        number = len(experiments) + 1
        experiments.append(
            {
                "id": f"C{number:02d}",
                "key": key,
                "name": template["name"],
                "tool": template["tool"],
                "script": template["file"],
                "hypothesis": template["hypothesis"],
                "steady_state_probes": template["steady_state"],
                "fault": template["fault"],
                "blast_radius": {
                    "allowed_targets": ["localhost", "127.0.0.1", "*.localhost", "host.docker.internal"],
                    "max_duration_seconds": template["max_duration_seconds"],
                },
                "abort_conditions": template["abort_conditions"],
                "rollback": template["rollback"],
                "expected_failure_rules": sorted(template["slugs"] & set().union(*(finding_slugs(f) for f in matched))),
                "findings": [
                    {"id": f["id"], "label": f["label"], "title": f["title"], "files": (f.get("files") or [])[:3]}
                    for f in matched
                ],
            }
        )
    return {
        "version": PLAN_VERSION,
        "target_repo": target_repo,
        "stack_trigger": stack_trigger,
        "default_base_url": DEFAULT_BASE_URL,
        "routes": routes or ["/"],
        "post_path": post_path,
        "evidence_backed_findings": len(backed),
        "hypotheses_ignored": sum(1 for f in findings if f.get("label") == "Hypothesis"),
        "experiments": experiments,
    }


def _readme(plan: dict[str, Any]) -> str:
    lines = [
        "# Chaos plan",
        "",
        f"Generated by RepoRover for `{plan.get('target_repo') or 'the analysed repository'}`.",
        f"Stack (deterministic fingerprint): {plan['stack_trigger']}",
        "",
        "## Safety",
        "- These are resilience tests for a copy of the app that **you run locally**.",
        "- Every script refuses to start unless `BASE_URL` is localhost, a loopback address, `*.localhost` or `host.docker.internal`.",
        "- `reporover chaos plan --run` also requires `--i-own-this-target` and refuses external URLs.",
        "- Load tests create real traffic. Run them against a disposable local instance, not shared infrastructure.",
        "",
        "## Experiments",
    ]
    if not plan["experiments"]:
        lines.append("No experiment was generated: no evidence-backed finding maps to a chaos template.")
    for experiment in plan["experiments"]:
        lines += [
            f"### {experiment['id']} {experiment['name']} ({experiment['tool']})",
            f"- **Script**: `{experiment['script']}`",
            f"- **Hypothesis**: {experiment['hypothesis']}",
            f"- **Fault**: {experiment['fault']['type']} {json.dumps(experiment['fault']['params'])}",
            f"- **Steady state**: {'; '.join(experiment['steady_state_probes'])}",
            f"- **Abort conditions**: {'; '.join(experiment['abort_conditions'])}",
            f"- **Rollback**: {experiment['rollback']}",
            "- **Justified by**: " + "; ".join(f"{f['id']} [{f['label']}] {f['title']}" for f in experiment["findings"]),
            "",
        ]
    lines += [
        "## Running by hand",
        "```",
        "cd playwright && npm init -y && npm i -D @playwright/test && npx playwright install chromium",
        f"BASE_URL={plan['default_base_url']} npx playwright test --config playwright.config.js",
        f"BASE_URL={plan['default_base_url']} k6 run k6/spike.js",
        "```",
        "Optional settings: `START_PATH`, `SUBMIT_SELECTOR`, `ACTION_SELECTOR`, `STATE_KEY`, `FILE_INPUT_SELECTOR`, "
        "`CHAOS_PATHS`, `CHAOS_POST_PATH`, `CHAOS_PEAK_VUS`, `CHAOS_SOAK_DURATION`.",
        "",
    ]
    return "\n".join(lines)


def plan_directory(out_root: str | os.PathLike, target_repo: str | None) -> Path:
    name = Path(target_repo).name if target_repo else "repo"
    safe = "".join(c if c.isalnum() or c in "-_." else "-" for c in name).strip(".-") or "repo"
    return Path(out_root) / safe / "chaos"


def generate_plan(
    findings: list[dict[str, Any]],
    stack_trigger: str = "unknown",
    target_repo: str | None = None,
    out_root: str | os.PathLike = "out",
    repo_name: str | None = None,
) -> tuple[Path, dict[str, Any]]:
    """Write plan.json, README.md and the scripts. Returns (directory, plan).

    `repo_name` names the output folder when the repository was analysed from
    a temporary clone whose own folder name means nothing.
    """
    routes, post_path = discover_routes(target_repo)
    selectors = discover_selectors(target_repo)
    plan = build_plan(findings, stack_trigger, target_repo, routes, post_path)
    plan["selectors"] = selectors
    if repo_name:
        plan["target_repo"] = repo_name
    directory = plan_directory(out_root, repo_name or target_repo)
    directory.mkdir(parents=True, exist_ok=True)

    for experiment in plan["experiments"]:
        template = TEMPLATES[experiment["key"]]
        script_path = directory / template["file"]
        script_path.parent.mkdir(parents=True, exist_ok=True)
        name = Path(template["file"]).stem.replace(".spec", "")
        script_path.write_text(
            _render(template, experiment, routes, post_path, name, selectors), encoding="utf-8", newline="\n")
    if any(e["tool"] == "playwright" for e in plan["experiments"]):
        (directory / "playwright").mkdir(exist_ok=True)
        (directory / "playwright" / "playwright.config.js").write_text(PLAYWRIGHT_CONFIG, encoding="utf-8", newline="\n")

    (directory / "plan.json").write_text(json.dumps(plan, indent=2), encoding="utf-8")
    (directory / "README.md").write_text(_readme(plan), encoding="utf-8", newline="\n")
    return directory, plan
