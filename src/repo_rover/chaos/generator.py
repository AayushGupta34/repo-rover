K6_COMMON = r"""import http from 'k6/http';
import { check, sleep } from 'k6';
import { Counter } from 'k6/metrics';
__GUARD__
const PATHS = (__ENV.CHAOS_PATHS ? __ENV.CHAOS_PATHS.split(',') : __PATHS__);
const rateLimited = new Counter('rate_limited_responses');
const serverErrors = new Counter('server_error_responses');

function visit() {
  const path = PATHS[Math.floor(Math.random() * PATHS.length)];
  const response = http.get(BASE_URL + path, { timeout: '10s', tags: { name: path } });
  if (response.status === 429) rateLimited.add(1);
  if (response.status >= 500 || response.status === 0) serverErrors.add(1);
  check(response, { 'no server error': (r) => r.status > 0 && r.status < 500 });
  return response;
}

export function setup() {
  // Steady state: the target must be healthy before any load is applied.
  const response = http.get(BASE_URL + PATHS[0], { timeout: '10s' });
  if (response.status === 0 || response.status >= 500) {
    throw new Error('Steady state not met: ' + BASE_URL + PATHS[0] + ' returned ' + response.status);
  }
}

export function handleSummary(data) {
  return { ['results/__NAME__.json']: JSON.stringify(data, null, 2), stdout: summaryLine(data) };
}

function summaryLine(data) {
  const m = data.metrics;
  const value = (name, field) => (m[name] && m[name].values[field] !== undefined ? m[name].values[field] : 0);
  return '\n__NAME__: requests=' + value('http_reqs', 'count') + ' failed=' + (value('http_req_failed', 'rate') * 100).toFixed(2) +
    '% p95=' + value('http_req_duration', 'p(95)').toFixed(0) + 'ms 429s=' + value('rate_limited_responses', 'count') +
    ' 5xx=' + value('server_error_responses', 'count') + '\n';
}
"""

