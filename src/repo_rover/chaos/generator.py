PW_MULTI_TAB = r"""// RepoRover chaos experiment: __EXPERIMENT_ID__ - stale tab overwrites newer data
// Findings: __FINDINGS__
// Hypothesis: __HYPOTHESIS__
const { test, expect } = require('@playwright/test');
__GUARD__
const START_PATH = process.env.START_PATH || '/';
const STATE_KEY = process.env.STATE_KEY || ''; // localStorage key holding app state; default: the largest
const ACTION_SELECTOR = process.env.ACTION_SELECTOR || ''; // a control in the app that saves
const MARKER = '__reporover_chaos_marker__';

test('a change made in one tab survives a save from an older tab', async ({ context }) => {
  const tabA = await context.newPage();
  const tabB = await context.newPage();
  await tabA.goto(BASE_URL + START_PATH);
  await tabB.goto(BASE_URL + START_PATH); // tab B now holds a copy of the state

  const key = await tabA.evaluate((wanted) => {
    if (wanted) return wanted;
    return Object.keys(localStorage).sort((a, b) => localStorage.getItem(b).length - localStorage.getItem(a).length)[0] || null;
  }, STATE_KEY);
  test.skip(!key, 'steady state not met: the app has stored nothing in localStorage yet');
  const original = await tabA.evaluate((k) => localStorage.getItem(k), key);

  // Fault: tab A records a change; tab B is now stale.
  await tabA.evaluate(([k, marker]) => {
    let state;
    try { state = JSON.parse(localStorage.getItem(k)); } catch (e) { state = null; }
    if (state && typeof state === 'object' && !Array.isArray(state)) state[marker] = Date.now();
    localStorage.setItem(k, state ? JSON.stringify(state) : localStorage.getItem(k) + marker);
  }, [key, MARKER]);

  // Observe: the stale tab saves.
  if (ACTION_SELECTOR) await tabB.locator(ACTION_SELECTOR).first().click();
  await tabB.evaluate(() => window.dispatchEvent(new Event('pagehide')));
  await tabB.waitForTimeout(500);

  const final = await tabA.evaluate((k) => localStorage.getItem(k), key);
  try {
    expect(final, 'the change from tab A must not be overwritten by the stale tab').toContain(MARKER);
  } finally {
    await tabA.evaluate(([k, value]) => localStorage.setItem(k, value), [key, original]); // rollback
  }
});
"""

